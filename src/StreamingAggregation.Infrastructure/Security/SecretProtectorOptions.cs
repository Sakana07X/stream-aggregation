    /// 注意：修改此值将导致已加密数据无法解密。
    /// </summary>
    public static readonly byte[] FixedEntropy = new byte[]
    {
        0x53, 0x74, 0x72, 0x65, 0x61, 0x6D, 0x41, 0x67, 0x67, 0x72, 0x65, 0x67, 0x61, 0x74, 0x69, 0x6F,
        0x6E, 0x2D, 0x44, 0x50, 0x41, 0x50, 0x49, 0x2D, 0x45, 0x6E, 0x74, 0x72, 0x6F, 0x70, 0x79, 0x2D,
        0x76, 0x31,
    };
}
